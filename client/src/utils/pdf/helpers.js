/* ======================================================= */
/* PARAGRAPH                                               */
/* ======================================================= */

export function drawParagraph(
  doc,
  text,
  x,
  y,
  width = PAGE.WIDTH - PAGE.MARGIN_X * 2
) {
  doc.setFont("helvetica", "normal");

  doc.setFontSize(FONT.body);

  doc.setTextColor(COLORS.black);

  const lines = doc.splitTextToSize(
    text || "",
    width
  );

  doc.text(lines, x, y);

  return (
    y +
    lines.length * LINE_HEIGHT
  );
}

/* ======================================================= */
/* BADGE                                                   */
/* ======================================================= */

export function drawBadge(
  doc,
  text,
  x,
  y,
  color = COLORS.emerald
) {
  const padding = 4;

  const badgeHeight = 8;

  const badgeWidth =
    doc.getTextWidth(text) +
    padding * 2;

  doc.setFillColor(color);

  doc.roundedRect(
    x,
    y - 5,
    badgeWidth,
    badgeHeight,
    4,
    4,
    "F"
  );

  doc.setFont("helvetica", "bold");

  doc.setFontSize(FONT.small);

  doc.setTextColor(COLORS.white);

  doc.text(
    text,
    x + padding,
    y + 0.5
  );

  return badgeWidth;
}
/* ======================================================= */
/* PROGRESS BAR                                            */
/* ======================================================= */

export function drawProgressBar(
  doc,
  label,
  value,
  x,
  y,
  width = 82
) {
  const safeValue = Math.max(
    0,
    Math.min(100, Number(value) || 0)
  );

  const barHeight = 5;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(FONT.small);
  doc.setTextColor(COLORS.slate);

  doc.text(label, x, y);

  doc.setFont("helvetica", "bold");
  doc.setTextColor(COLORS.navy);

  doc.text(
    `${safeValue}%`,
    x + width + 6,
    y,
    {
      align: "left",
    }
  );

  // Background

  doc.setFillColor(235, 238, 242);

  doc.roundedRect(
    x,
    y + 4,
    width,
    barHeight,
    3,
    3,
    "F"
  );

  // Progress

  doc.setFillColor(COLORS.emerald);

  doc.roundedRect(
    x,
    y + 4,
    (width * safeValue) / 100,
    barHeight,
    3,
    3,
    "F"
  );

  return y + 14;
}

/* ======================================================= */
/* SKILL PILLS                                             */
/* ======================================================= */

export function drawPills(
  doc,
  items = [],
  x,
  y,
  maxWidth = 170
) {
  let currentX = x;

  let currentY = y;

  items.forEach((item) => {
    const text = String(item);

    const pillWidth =
      doc.getTextWidth(text) + 12;

    if (
      currentX + pillWidth >
      x + maxWidth
    ) {
      currentX = x;
      currentY += 11;
    }

    doc.setFillColor(248, 250, 252);

    doc.setDrawColor(COLORS.border);

    doc.roundedRect(
      currentX,
      currentY - 4,
      pillWidth,
      8,
      4,
      4,
      "FD"
    );

    doc.setFont("helvetica", "bold");
    doc.setFontSize(FONT.small);
    doc.setTextColor(COLORS.navy);

    doc.text(
      text,
      currentX + 6,
      currentY + 1
    );

    currentX += pillWidth + 5;
  });

  return currentY + 14;
}

