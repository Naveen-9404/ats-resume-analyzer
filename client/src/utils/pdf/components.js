/* STRENGTHS                                               */
/* ======================================================= */

export function drawStrengths(
  doc,
  report,
  y
) {
  const strengths =
    report.strengths?.length
      ? report.strengths
      : ["No strengths identified."];

  const totalLines = strengths.reduce(
    (sum, item) =>
      sum +
      doc.splitTextToSize(item, 155).length,
    0
  );

  const cardHeight = Math.max(
    40,
    totalLines * 6 +
      strengths.length * 4 +
      16
  );

  y = ensurePage(
    doc,
    y,
    cardHeight + 20
  );

  y = drawSectionTitle(
    doc,
    "Strengths",
    y
  );

  drawCard(
    doc,
    PAGE.MARGIN_X,
    y,
    178,
    cardHeight
  );

  let currentY = y + 12;

  strengths.forEach((item) => {
    const lines =
      doc.splitTextToSize(
        item,
        152
      );

    doc.setFont(
      "helvetica",
      "bold"
    );

    doc.setFontSize(11);

    doc.setTextColor(
      COLORS.emerald
    );

    doc.text(
      "-",
      24,
      currentY
    );

    doc.setFont(
      "helvetica",
      "normal"
    );

    doc.setTextColor(
      COLORS.black
    );

    doc.text(
      lines,
      31,
      currentY
    );

    currentY +=
      lines.length * 6 + 3;
  });

  return y + cardHeight + 12;
}

