/* RECRUITER VERDICT                                       */
/* ======================================================= */

export function drawVerdict(
  doc,
  report,
  y
) {
  y = ensurePage(doc, y, 90);

  y = drawSectionTitle(
    doc,
    "Recruiter Verdict",
    y
  );

  drawCard(
    doc,
    PAGE.MARGIN_X,
    y,
    178,
    68
  );

  const verdict =
    report.recruiterVerdict || {};

  let badgeColor =
    COLORS.emerald;

  switch (
    verdict.rating
  ) {
    case "Excellent Match":
      badgeColor =
        COLORS.emerald;
      break;

    case "Good Match":
      badgeColor =
        COLORS.blue;
      break;

    case "Average Match":
      badgeColor =
        COLORS.amber;
      break;

    case "Poor Match":
      badgeColor =
        COLORS.red;
      break;

    default:
      badgeColor =
        COLORS.slate;
  }

  /* Badge */

  doc.setFillColor(
    badgeColor
  );

  doc.roundedRect(
    22,
    y + 10,
    58,
    12,
    4,
    4,
    "F"
  );

  doc.setFont(
    "helvetica",
    "bold"
  );

  doc.setFontSize(12);

  doc.setTextColor(
    COLORS.white
  );

  doc.text(
    verdict.rating ||
      "Good Match",
    51,
    y + 18,
    {
      align: "center",
    }
  );

  /* ATS */

  doc.setFontSize(36);
  doc.setTextColor(
    COLORS.navy
  );

  doc.text(
    `${report.atsScore || 0}%`,
    150,
    y + 20,
    {
      align: "center",
    }
  );

  doc.setFontSize(10);
  doc.setTextColor(
    COLORS.slate
  );

  doc.text(
    "ATS SCORE",
    150,
    y + 28,
    {
      align: "center",
    }
  );

  /* Divider */

  doc.setDrawColor(
    COLORS.border
  );

  doc.line(
    22,
    y + 36,
    188,
    y + 36
  );

  /* Reason */

  doc.setFont(
    "helvetica",
    "bold"
  );

  doc.setFontSize(11);
  doc.setTextColor(
    COLORS.navy
  );

  doc.text(
    "Recruiter's Assessment",
    22,
    y + 46
  );

  drawParagraph(
    doc,
    verdict.reason ||
      "The resume demonstrates good ATS compatibility and shows strong potential for interview consideration.",
    22,
    y + 54,
    165
  );

  return y + 82;
}