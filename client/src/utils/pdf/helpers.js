import { COLORS, FONT, PAGE, SPACING, CARD } from "./theme";

/* ======================================================= */
/* LAYOUT CONSTANTS                                        */
/* ======================================================= */

const SECTION_GAP = 16;
const CARD_PADDING = 8;
const LINE_HEIGHT = 6;

/* ======================================================= */
/* PAGE MANAGEMENT                                         */
/* ======================================================= */

export function ensurePage(
  doc,
  y,
  requiredHeight = 25
) {
  const bottomLimit =
    PAGE.HEIGHT - PAGE.MARGIN_Y;

  if (y + requiredHeight > bottomLimit) {
    doc.addPage();

    drawHeader(doc);

    return PAGE.MARGIN_Y + 18;
  }

  return y;
}

/* ======================================================= */
/* HEADER                                                  */
/* ======================================================= */

export function drawHeader(doc) {
  doc.setFillColor(COLORS.navy);

  doc.rect(
    0,
    0,
    PAGE.WIDTH,
    18,
    "F"
  );

  doc.setFont("helvetica", "bold");
  doc.setFontSize(FONT.subHeading);
  doc.setTextColor(COLORS.white);

  doc.text(
    "VectorCV",
    PAGE.MARGIN_X,
    11
  );

  doc.setFont("helvetica", "normal");
  doc.setFontSize(FONT.small);

  doc.text(
    "AI-Powered Career Intelligence",
    PAGE.WIDTH - PAGE.MARGIN_X,
    11,
    {
      align: "right",
    }
  );
}

/* ======================================================= */
/* FOOTER                                                  */
/* ======================================================= */

export function drawFooter(doc) {
  const totalPages =
    doc.getNumberOfPages();

  for (
    let page = 1;
    page <= totalPages;
    page++
  ) {
    doc.setPage(page);

    doc.setDrawColor(COLORS.border);

    doc.line(
      PAGE.MARGIN_X,
      PAGE.HEIGHT - 14,
      PAGE.WIDTH - PAGE.MARGIN_X,
      PAGE.HEIGHT - 14
    );

    doc.setFont("helvetica", "normal");
    doc.setFontSize(FONT.small);
    doc.setTextColor(COLORS.slate);

    doc.text(
      "Generated by VectorCV",
      PAGE.MARGIN_X,
      PAGE.HEIGHT - 8
    );

    doc.text(
      `Page ${page} of ${totalPages}`,
      PAGE.WIDTH - PAGE.MARGIN_X,
      PAGE.HEIGHT - 8,
      {
        align: "right",
      }
    );
  }
}

